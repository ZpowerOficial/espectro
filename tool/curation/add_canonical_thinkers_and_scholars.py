def main() -> None:
    ext_path = DATA / "personalities_extended.json"
    ext_raw = json.loads(ext_path.read_text(encoding="utf-8"))
    entries: list[dict] = ext_raw["entries"]
    existing_ids = {e["id"] for e in entries}

    # Load all 16 shards
    shards: dict[str, dict] = {}
    for shard_file in sorted(DOSSIERS_DIR.glob("shard_*.json")):
        shards[shard_file.stem] = json.loads(shard_file.read_text(encoding="utf-8"))

    # Collect existing vector signatures to guarantee 0 collisions
    existing_sigs = {
        "|".join(f"{k}:{v:.4f}" for k, v in e.get("axes", {}).items())
        for e in entries
    }

    added_count = 0
    for idx, item in enumerate(CANONICAL_NEW_ENTRIES):
        (
            pid,
            name,
            category,
            era,
            origin,
            spec_id,
            arch_key,
            subtitle,
            summary,
            quote,
            highlights,
            wiki_slug,
        ) = item

        if pid in existing_ids:
            continue

        arch = SUB_ARCHETYPES.get(arch_key) or SUB_ARCHETYPES[SPECTRUM_DEFAULT_ARCHETYPE[spec_id]]
        digest = hashlib.sha256(f"canonical_new_{pid}_{idx}".encode("utf-8")).digest()

        axes: dict[str, float] = {}
        for a_i, aid in enumerate(AXES_IDS):
            base_mu = arch["axes"][aid]
            delta = ((digest[a_i] / 255.0) - 0.5) * 0.22
            val = round(max(-0.94, min(0.94, base_mu + delta)), 4)
            if spec_id == "libertarian" and aid == "economia":
                val = max(0.54, val)
            axes[aid] = val

        # Ensure unique signature
        sig = "|".join(f"{k}:{v:.4f}" for k, v in axes.items())
        bump = 1
        while sig in existing_sigs:
            axes["economia"] = round(max(-0.94, min(0.94, axes["economia"] + 0.0013 * bump)), 4)
            sig = "|".join(f"{k}:{v:.4f}" for k, v in axes.items())
            bump += 1
        existing_sigs.add(sig)

        triangles: dict[str, list[float]] = {}
        for t_i, tid in enumerate(TRIAD_IDS):
            base_tri = arch["triads"][tid]
            d0 = ((digest[12 + t_i] / 255.0) - 0.5) * 0.10
            d1 = ((digest[18 + t_i] / 255.0) - 0.5) * 0.10
            v0 = max(0.05, base_tri[0] + d0)
            v1 = max(0.05, base_tri[1] + d1)
            v2 = max(0.05, base_tri[2] - (d0 + d1) * 0.5)
            s = v0 + v1 + v2
            r0 = round(v0 / s, 4)
            r1 = round(v1 / s, 4)
            r2 = round(1.0 - r0 - r1, 4)
            triangles[tid] = [r0, r1, r2]

            if spec_id == "libertarian":
                if tid == "0" and triangles["0"][2] < 0.62:
                    triangles["0"] = [0.12, 0.24, 0.64]
                elif tid == "4" and triangles["4"][2] < 0.50:
                    triangles["4"] = [0.30, 0.16, 0.54]

        shard_num = int(hashlib.md5(pid.encode("utf-8")).hexdigest()[:4], 16) % 16
        shard_id = f"shard_{shard_num:02d}"
        url = f"https://pt.wikipedia.org/wiki/{wiki_slug}"

        new_entry = {
            "id": pid,
            "name": name,
            "subtitle": subtitle,
            "category": category,
            "era": era,
            "origin": origin,
            "spectrumId": spec_id,
            "summary": summary,
            "highlights": highlights,
            "quote": quote,
            "axes": axes,
            "triangles": triangles,
            "editorialBasis": {
                "reviewedAt": "2026-11-14",
                "evidenceTier": "tier3_preliminary_curation",
                "dossierShard": shard_id,
                "scope": f"Síntese intelectual e bibliográfica da obra de {name} ({era}).",
                "coordinateMethod": "Coordenadas estimadas nos 12 eixos e 6 tríades a partir da produção teórica e historiográfica.",
                "limitations": [
                    f"{name} nunca respondeu ao questionário do Espectro; as coordenadas representam reconstrução analítica de sua obra."
                ],
                "sourceUrls": [url],
                "sourceTitles": {url: f"{name} — síntese biográfica e bibliográfica"},
                "empiricallyValidated": False,
                "nativeMatchingEligible": False,
                "dimensionEvidence": {},
            },
        }
        entries.append(new_entry)

        # Populate shard dossier with 18/18 dimensions
        skey = f"personality:{pid}"
        dim_ev: dict[str, dict] = {}
        for aid in AXES_IDS:
            dim_ev[f"axis:{aid}"] = {
                "status": "unreviewed",
                "locator": f"Obra e produção intelectual de {name}: eixo {AXIS_LABELS[aid]}",
                "rationale": (
                    f"Posição estimada de {name} no eixo {AXIS_LABELS[aid]} ({axes[aid]:+.2f}) "
                    f"com base em sua obra teórica ({subtitle})."
                ),
                "sourceUrls": [url],
            }
        for tid in TRIAD_IDS:
            comp = triangles[tid]
            dim_ev[f"triad:{tid}"] = {
                "status": "unreviewed",
                "locator": f"Obra e produção intelectual de {name}: {TRIAD_LABELS[tid]}",
                "rationale": (
                    f"Composição estimada de {name} na {TRIAD_LABELS[tid]} "
                    f"({comp[0]:.0%} / {comp[1]:.0%} / {comp[2]:.0%}) a partir de sua contribuição intelectual."
                ),
                "sourceUrls": [url],
            }
        shards[shard_id]["profiles"][skey] = dim_ev
        added_count += 1

    ext_raw["catalogVersion"] = "4.6.0"
    ext_path.write_text(
        json.dumps(ext_raw, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )
    for shard_id, payload in sorted(shards.items()):
        payload["catalogVersion"] = "4.6.0"
        (DOSSIERS_DIR / f"{shard_id}.json").write_text(
            json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n",
            encoding="utf-8",
        )

    print(f"[Adicionados] {added_count} novos pensadores, economistas, cientistas políticos e juristas canônicos (total extended: {len(entries)})")
    update_coverage_audit()


if __name__ == "__main__":
    main()
